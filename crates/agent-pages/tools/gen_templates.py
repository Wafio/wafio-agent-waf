def raw_after(src, start_pat, lit_prefix):
    i = src.index(start_pat)
    j = src.index(lit_prefix, i) + len(lit_prefix)
    k = src.index('`', j)
    return src[j:k]
ch = open(root + '/internal/engine/challenge.go').read()
ag = open(root + '/internal/wafagent/agent.go').read()
hd = open(root + '/internal/wafagent/challenge_handler.go').read()
items = []
for m in re.finditer(r'const (\w+) = `(.*?)`', ch, re.S):
    items.append((m.group(1), m.group(2)))
for fn in ['BuildJSChallengePage', 'BuildTurnstileChallengePage', 'BuildHCaptchaChallengePage',
           'BuildAdaptiveJSChallengePage', 'BuildSimulationSuccessPage', 'buildJSChallengeScript']:
    items.append((fn + 'Fmt', raw_after(ch, 'func ' + fn + '(', 'fmt.Sprintf(`')))
items.append(('BuildClickPuzzleWidgetFmt', raw_after(ch, 'return fmt.Sprintf(`%s<div class="wafio-puzzle">', 'return fmt.Sprintf(`')))
items.append(('WAFBlockDefaultHTMLFmt', raw_after(ag, 'func buildBlockResponse(', 'Body: fmt.Sprintf(`')))
items.append(('IPRepBlockDefaultHTML', raw_after(hd, 'func serveIPRepBlockPage(', 'ctx.SetBodyString(`')))
def snake(n):
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', n)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    return s.upper()
